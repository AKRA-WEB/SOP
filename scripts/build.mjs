const cleanOutput = (html) => html.replace(/[ \t]+$/gm, "");
const outputs = new Map([
  [path.join(ROOT, "index.html"), cleanOutput(renderIndex())],
  [path.join(ROOT, "inventory.html"), cleanOutput(renderInventory())],
  ...sops.map((sop) => [path.join(ROOT, "sops", `${sop.slug}.html`), cleanOutput(renderSop(sop))])
]);
const sopOutputDir = path.join(ROOT, "sops");
const checkOnly = process.argv.includes("--check");
const mismatches = [];

fs.mkdirSync(sopOutputDir, { recursive: true });
for (const [file, expected] of outputs) {
  if (checkOnly) {
    if (!fs.existsSync(file) || fs.readFileSync(file, "utf8") !== expected) {
      mismatches.push(`${path.relative(ROOT, file)} is missing or stale`);
    }
  } else {
    fs.writeFileSync(file, expected, "utf8");
  }
}

const expectedSopFiles = new Set([...outputs.keys()].filter((file) => path.dirname(file) === sopOutputDir));
for (const name of fs.readdirSync(sopOutputDir).filter((entry) => entry.endsWith(".html"))) {
  const file = path.join(sopOutputDir, name);
  if (expectedSopFiles.has(file)) continue;
  const existing = fs.readFileSync(file, "utf8");
  if (checkOnly) {
    mismatches.push(`${path.relative(ROOT, file)} is an orphan generated page`);
  } else if (existing.startsWith(GENERATED_MARKER)) {
    fs.rmSync(file);
  } else {
    throw new Error(`Refusing to remove non-generated orphan ${path.relative(ROOT, file)}`);
  }
}

if (mismatches.length) {
  console.error("Generated output is not in sync with canonical content:");
  mismatches.forEach((mismatch) => console.error(`- ${mismatch}`));
  process.exit(1);
}

console.log(`${checkOnly ? "Checked" : "Built"} index, inventory, and ${sops.length} SOP pages.`);
