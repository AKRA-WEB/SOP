import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const SCRIPT_DIR = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(SCRIPT_DIR, "..");
const portfolio = JSON.parse(fs.readFileSync(path.join(ROOT, "content", "portfolio.json"), "utf8"));
const contentDir = path.join(ROOT, "content", "sops");
const packs = fs.readdirSync(contentDir)
  .filter((name) => name.endsWith(".json"))
  .sort()
  .map((name) => JSON.parse(fs.readFileSync(path.join(contentDir, name), "utf8")));
const sops = packs.flatMap((pack) => pack.sops.map((sop) => ({ ...sop, app: pack.app, appName: pack.appName, sourceVersion: pack.sourceVersion })));
const sopById = new Map(sops.map((sop) => [sop.id, sop]));
const GENERATED_MARKER = "<!-- Generated by scripts/build.mjs; edit canonical JSON instead. -->\n";

function escapeHtml(value) {
  return String(value ?? "")
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&#39;");
}

function list(items, className = "") {
  return `<ul${className ? ` class="${className}"` : ""}>${items.map((item) => `<li>${escapeHtml(item)}</li>`).join("")}</ul>`;
}

